// Regenerate src/render/building-asset-index.js from the building assets on disk.
// Run after generating/curating building assets (roofs, tiles, dressing) for any biome:
//   node scripts/gen-building-asset-index.mjs
import fs from 'fs';
import path from 'path';
const ROOT = 'assets/pixelab/buildings';
const out = [];
function walk(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p);
    else if (e.name.endsWith('.png')) out.push(path.relative(ROOT, p).split(path.sep).join('/'));
  }
}
walk(ROOT);
out.sort();
const header = `// AUTO-GENERATED by scripts/gen-building-asset-index.mjs — do not edit.
// A Set of every building asset PATH that EXISTS on disk, relative to /assets/pixelab/buildings/.
// The image loaders (d3-props, vine-render, building-occluder roof/_imageCache) consult this BEFORE
// creating an Image, so they never request a 404 (partial biomes = forest/taiga/swamp/... ) and never
// run an expensive empty dressing/roof pass for an asset that was never generated.
`;
const body = header + 'export const BUILDING_ASSET_INDEX = new Set(' + JSON.stringify(out) + ');\n\n' +
`const _PREFIX = '/assets/pixelab/buildings/';
// True if \`url\` points at a building asset that EXISTS on disk (or is not a building-asset URL at all —
// unknown prefixes are never gated, so this can only ADD skips for known-absent files, never hide art the
// loader would otherwise find). Loaders call this before \`new Image()\` to avoid 404s + empty passes.
export function buildingAssetExists(url) {
  if (typeof url !== 'string') return true;
  const i = url.indexOf(_PREFIX);
  if (i < 0) return true;            // not under the buildings root → don't gate
  return BUILDING_ASSET_INDEX.has(url.slice(i + _PREFIX.length));
}
`;
fs.writeFileSync('src/render/building-asset-index.js', body);
console.log('wrote src/render/building-asset-index.js with', out.length, 'paths');
