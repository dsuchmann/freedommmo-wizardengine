// scripts/gen-dressing-vmap.mjs
// Scans assets/pixelab/buildings/dressing and writes src/world/dressing-vmap.js.
// Re-run whenever _dressing_curation.json changes or new base__vN.png sprites land on disk.
//
// Output shape: { "<biome>/<prop>": [allowed_disk_indices] }
//   • Entry present + non-empty  → only those disk indices are in rotation.
//   • Entry present + empty []   → prop is fully omitted (renderer skips it).
//   • No entry                   → uncurated; d3-props falls back to all on-disk variants.
//     (No props should be uncurated once this generator has run; every prop on disk gets an entry.)
import fs from 'fs';
import path from 'path';
import url from 'url';
import { loadCuration, omitSetMap } from './lib/field-curation.mjs';

const ROOT = path.join(path.dirname(url.fileURLToPath(import.meta.url)), '..');
const DRESSING_DIR = path.join(ROOT, 'assets/pixelab/buildings/dressing');
const OUT = path.join(ROOT, 'src/world/dressing-vmap.js');

const FILE_RE = /^base__v(\d+)\.png$/;

const OMIT = omitSetMap(loadCuration('dressing')); // "biome/prop" -> Set(omitted variant indices)
const allowed = {};

for (const biome of fs.readdirSync(DRESSING_DIR).sort()) {
  if (biome.startsWith('_')) continue;
  const bdir = path.join(DRESSING_DIR, biome);
  let bst; try { bst = fs.statSync(bdir); } catch { continue; }
  if (!bst.isDirectory()) continue;

  for (const prop of fs.readdirSync(bdir).sort()) {
    if (prop.startsWith('_')) continue;
    const pdir = path.join(bdir, prop);
    let pst; try { pst = fs.statSync(pdir); } catch { continue; }
    if (!pst.isDirectory()) continue;

    const present = fs.readdirSync(pdir)
      .map(f => { const m = f.match(FILE_RE); return m ? parseInt(m[1], 10) : null; })
      .filter(v => v !== null)
      .sort((a, b) => a - b);

    if (!present.length) continue; // no base sprites on disk → skip entirely (uncurated absent = honest absent)

    const omitSet = OMIT.get(biome + '/' + prop) || new Set();
    // Emit even if vmapAllowed is empty — renderer distinguishes [] (fully culled) from
    // no-entry (uncurated → fallback). Same lesson as F2 (sf-catalog).
    const vmapAllowed = present.filter(v => !omitSet.has(v));
    allowed[biome + '/' + prop] = vmapAllowed;
  }
}

const body = 'export const DRESSING_ALLOWED = ' + JSON.stringify(allowed, null, 1) + ';\n';
fs.writeFileSync(OUT,
  '// AUTO-GENERATED by scripts/gen-dressing-vmap.mjs — do not edit.\n' +
  '// Re-run whenever _dressing_curation.json changes or new base__vN.png sprites land on disk.\n' +
  body
);
const n = Object.keys(allowed).length;
console.log(`wrote ${OUT}: ${n} prop entries`);
