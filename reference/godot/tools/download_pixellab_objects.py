# Deduplicate
seen = set()
unique_objects = []
for obj_id, desc, category in OBJECTS:
    if obj_id not in seen:
        seen.add(obj_id)
        unique_objects.append((obj_id, desc, category))

print(f"Total unique objects to download: {len(unique_objects)}")

# Count by category
from collections import Counter
cat_counts = Counter(cat for _, _, cat in unique_objects)
for cat, count in sorted(cat_counts.items()):
    print(f"  {cat}: {count}")

# Generate download commands
download_url = "https://api.pixellab.ai/mcp/objects/{}/download"
success = 0
failed = 0

for obj_id, desc, category in unique_objects:
    dest_dir = BASE_DIR / category
    dest_dir.mkdir(parents=True, exist_ok=True)

    # Clean filename from description
    clean_desc = re.sub(r'[^a-z0-9_]', '_', desc.lower().strip())
    clean_desc = re.sub(r'_+', '_', clean_desc).strip('_')
    filename = f"{clean_desc}_{obj_id[:8]}.png"
    dest_path = dest_dir / filename

    if dest_path.exists():
        success += 1
        continue

    url = download_url.format(obj_id)
    try:
        result = subprocess.run(
            ["curl", "-sL", "-o", str(dest_path), url],
            timeout=30,
            capture_output=True
        )
        if result.returncode == 0 and dest_path.exists() and dest_path.stat().st_size > 0:
            success += 1
        else:
            failed += 1
            if dest_path.exists():
                dest_path.unlink()
    except Exception as e:
        failed += 1
        print(f"  FAILED: {obj_id} - {e}")

print(f"\nDownload complete: {success} success, {failed} failed out of {len(unique_objects)} unique objects")

# Write manifest
manifest = {}
for obj_id, desc, category in unique_objects:
    clean_desc = re.sub(r'[^a-z0-9_]', '_', desc.lower().strip())
    clean_desc = re.sub(r'_+', '_', clean_desc).strip('_')
    filename = f"{clean_desc}_{obj_id[:8]}.png"
    if category not in manifest:
        manifest[category] = []
    manifest[category].append({
        "id": obj_id,
        "description": desc,
        "filename": filename,
        "path": f"assets/catalog/objects/{category}/{filename}"
    })

manifest_path = BASE_DIR / "manifest.json"
with open(manifest_path, "w") as f:
    json.dump(manifest, f, indent=2)
print(f"Manifest written to {manifest_path}")
