DOWNLOADED=0
FAILED=0
SKIPPED=0

for idx in "${!OBJECTS[@]}"; do
  OBJ_ID="${OBJECTS[$idx]}"
  OBJ_NUM=$((idx + 1))
  DIR="$STAGING/$OBJ_ID"

  # Skip if already downloaded
  if [ -d "$DIR" ] && ls "$DIR"/*.png 1>/dev/null 2>&1; then
    SKIPPED=$((SKIPPED + 1))
    continue
  fi

  mkdir -p "$DIR"

  # Download frames 0-63 in parallel, silently skip 404s
  for i in $(seq 0 63); do
    URL="${BASE_URL}/${OBJ_ID}/rotations/frame_${i}.png"
    OUT="$DIR/frame_${i}.png"
    curl -sf -o "$OUT" "$URL" &

    # Limit to 20 concurrent downloads
    if (( (i + 1) % 20 == 0 )); then
      wait
    fi
  done
  wait

  # Remove empty/failed files (curl -f won't create them but just in case)
  for f in "$DIR"/frame_*.png; do
    if [ -f "$f" ] && [ ! -s "$f" ]; then
      rm "$f"
    fi
  done

  COUNT=$(ls "$DIR"/*.png 2>/dev/null | wc -l)
  if [ "$COUNT" -gt 0 ]; then
    DOWNLOADED=$((DOWNLOADED + COUNT))
    if (( OBJ_NUM % 25 == 0 )); then
      echo "Progress: $OBJ_NUM/$TOTAL objects processed, $DOWNLOADED frames downloaded so far"
    fi
  else
    FAILED=$((FAILED + 1))
    rmdir "$DIR" 2>/dev/null
  fi
done

